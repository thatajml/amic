"""Size Tier 1's uncertain band so Tier 2 sees a target share of ALL validation traffic
(brief 6.2: Tier 2 on at most 10-15% of traffic). Writes the full-cascade config.

    python scripts/tune_band.py --rate 0.12        # -> configs/ablations/full.yaml

Validation split only; the test split is never looked at. The band contains tau* = 1/(1+lambda).

Isotonic calibration makes p a step function (8 distinct values on val, 53 of 134 rows at one
of them), so a band holding exactly the target share usually does not exist. The brief sets a
CEILING (Tier 2 on at most 10-15% of traffic), so this picks the widest band whose validation
share is <= the target, with edges at midpoints between adjacent p levels (robust to rounding).
(thresholds.band_for_rate grows until it REACHES the target, which overshoots on step data.)
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

from amic.contracts.config import load_settings
from amic.control.thresholds import tau_star, widest_band_under
from amic.control.tier1 import Tier1Model
from amic.eval.replay import load_dataset


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--rate", type=float, default=0.12)
    ap.add_argument("--tier1", default="models/tier1.joblib")
    ap.add_argument("--out", default="configs/ablations/full.yaml")
    a = ap.parse_args()

    s = load_settings("configs/base.yaml")
    tau = tau_star(s.gate.lam)
    val = load_dataset("edu").query("split == 'val'")
    t1rows = val[val.tier0_rule == "abstain"]
    model = Tier1Model.load(a.tier1)
    p = model.predict_many(t1rows[model.features].to_numpy(np.float32))[0]
    lo, hi = widest_band_under(p, tau, a.rate * len(val))
    in_band = int(((p >= lo) & (p <= hi)).sum())
    print(
        f"val: {len(val)} probes, {len(t1rows)} reach Tier 1; tau*={tau:.3f}; "
        f"band [{lo:.3f}, {hi:.3f}] holds {in_band} = {in_band / len(val):.1%} of all val traffic"
    )
    text = f"""# Full cascade (pre-registered T1/T2, docs/PLAN.md section 9): Tier 0 -> Tier 1 -> Tier 2.
# Band generated by scripts/tune_band.py --rate {a.rate} on the VALIDATION split only:
# [{lo:.3f}, {hi:.3f}] around tau* = {tau:.3f} holds {in_band}/{len(val)} = {in_band / len(val):.1%} of val traffic.
# Isotonic p has few distinct levels, so this is the widest band whose val share is <= the
# target (the brief sets a ceiling); see the script docstring.
# Tier 2 is also hard-capped at gate.tier2_max_rate of all traffic and fails open to SHALLOW.
ablation:
  tiers: full
gate:
  band_low_offset: {tau - lo:.4f}
  band_high_offset: {hi - tau:.4f}
  tier2_max_rate: {a.rate}
  tier2_timeout_ms: 800
"""
    Path(a.out).write_text(text, encoding="utf-8")
    print(f"-> {a.out}")


if __name__ == "__main__":
    main()
